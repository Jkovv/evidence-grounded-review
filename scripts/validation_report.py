"""Generate the traceability matrix and test report in docs/validation from the tests.

    python scripts/validation_report.py --junit results/test-report.xml --coverage coverage.xml

Requirements are read from docs/validation/requirements.md (lines starting with
"REQ-"), the tests that give evidence for each from the @pytest.mark.req
markers in tests/, and the outcomes from the JUnit file written by pytest.
"""

from __future__ import annotations

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = re.compile(r'@pytest\.mark\.req\("(REQ-\d{3})"\)')
DEF = re.compile(r"^def (test_\w+)", re.MULTILINE)


def requirements(path: Path) -> list[tuple[str, str]]:
    """(id, title) for every requirement line in requirements.md."""
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\| (REQ-\d{3}) \| ([^|]+) \|", line)
        if m:
            out.append((m.group(1), m.group(2).strip()))
    return out


def markers(tests_dir: Path) -> dict[str, list[str]]:
    """Requirement id to the tests marked with it, as file::name."""
    out: dict[str, list[str]] = defaultdict(list)
    for path in sorted(tests_dir.glob("test_*.py")):
        text = path.read_text(encoding="utf-8")
        for m in MARK.finditer(text):
            d = DEF.search(text, m.end())
            if d:
                out[m.group(1)].append(f"{path.name}::{d.group(1)}")
    return out


def outcomes(junit: Path | None) -> dict[str, str]:
    """Test name (file::name) to passed, failed, error or skipped."""
    if junit is None or not junit.exists():
        return {}
    out: dict[str, str] = {}
    for case in ET.parse(junit).getroot().iter("testcase"):
        name = re.sub(r"\[.*\]$", "", case.get("name", ""))
        file = Path(case.get("classname", "").replace(".", "/") + ".py").name
        key = f"{file}::{name}"
        status = "passed"
        for child in case:
            if child.tag in ("failure", "error", "skipped"):
                status = child.tag if child.tag != "failure" else "failed"
        if out.get(key) != "failed":
            out[key] = status
    return out


def coverage(path: Path | None) -> str:
    """Line coverage of the package from a Cobertura file, as a percentage string."""
    if path is None or not path.exists():
        return "not measured"
    rate = float(ET.parse(path).getroot().get("line-rate", "0"))
    return f"{100 * rate:.1f}%"


def main() -> int:
    """Write traceability_matrix.md and test_report.md."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--junit", type=Path, default=ROOT / "results" / "test-report.xml")
    parser.add_argument("--coverage", type=Path, default=ROOT / "coverage.xml")
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "validation")
    args = parser.parse_args()
    reqs = requirements(args.out / "requirements.md")
    marks = markers(ROOT / "tests")
    results = outcomes(args.junit)
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "# Traceability matrix",
        "",
        f"Generated by `scripts/validation_report.py` on {now}. Each requirement in",
        "`requirements.md` is linked to the tests that carry its marker; the outcome",
        "column comes from the last pytest run (`results/test-report.xml`).",
        "",
        "| Requirement | Title | Tests | Outcome |",
        "|---|---|---|---|",
    ]
    untraced = []
    for rid, title in reqs:
        tests = marks.get(rid, [])
        if not tests:
            untraced.append(rid)
        status = [results.get(t, "not run") for t in tests]
        if not tests:
            outcome = "no test"
        elif all(s == "passed" for s in status):
            outcome = f"passed ({len(tests)})"
        elif any(s == "not run" for s in status):
            outcome = "not run"
        else:
            outcome = "FAILED"
        listed = "<br>".join(f"`{t}`" for t in tests) or "none"
        lines.append(f"| {rid} | {title} | {listed} | {outcome} |")
    extra = sorted(set(marks) - {r for r, _ in reqs})
    if extra:
        lines += ["", f"Markers without a requirement: {', '.join(extra)}."]
    (args.out / "traceability_matrix.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8", newline="\n"
    )

    counts: dict[str, int] = defaultdict(int)
    for s in results.values():
        counts[s] += 1
    report = [
        "# Test report",
        "",
        f"Generated by `scripts/validation_report.py` on {now} from `results/test-report.xml`.",
        "",
        f"* Tests: {len(results)} ({counts['passed']} passed, {counts['failed']} failed, "
        f"{counts['error']} errors, {counts['skipped']} skipped)",
        f"* Line coverage of `egr`: {coverage(args.coverage)}",
        f"* Requirements: {len(reqs)}, with tests: {len(reqs) - len(untraced)}",
        "",
        "| Test | Outcome |",
        "|---|---|",
    ]
    for key in sorted(results):
        report.append(f"| `{key}` | {results[key]} |")
    (args.out / "test_report.md").write_text(
        "\n".join(report) + "\n", encoding="utf-8", newline="\n"
    )
    print(f"{len(reqs)} requirements, {len(results)} tests, coverage {coverage(args.coverage)}")
    if untraced:
        print(f"requirements without a test: {', '.join(untraced)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
